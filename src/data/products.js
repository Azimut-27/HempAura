export const getProductById = (id) => {
  for (const product of products) {
    if (product.id === id) return product;
    if (product.variants) {
      const variant = product.variants.find((v) => v.id === id);
      if (variant) {
        return {
          ...product,
          ...variant,
          parentId: product.id,
          name: `${product.name} (${variant.label})`,
          variantLabel: variant.label,
        };
      }
    }
  }
  return undefined;
};
